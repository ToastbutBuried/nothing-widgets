#!/usr/bin/env python3
"""Generates app/src/main/res/drawable/eq_anim.xml: the artwork widget's mini dot "eq" (4 columns x up to 5 dots),
modelled on Nothing's music widget. Not audio driven: each column walks through random heights on its own loop
length, so the combined pattern practically never repeats. The launcher plays it (indeterminate ProgressBar),
the app never pushes frames. Re-run after changing the numbers: python3 tools/gen_eq.py"""
import random, os

COLS, ROWS = 4, 5
PITCH, R = 5.7, 2.0          # dp: dot spacing and radius (measured from Nothing's widget)
STEP = 140                   # ms per height change
FADE = 70                    # ms dot fade in/out
LOOP_STEPS = [50, 57, 46, 61]  # per column, different lengths so the columns drift apart
COLOR = "#EB5C5C5C"          # Nothing grey, barely transparent
random.seed(7)

W = (COLS - 1) * PITCH + 2 * R
H = (ROWS - 1) * PITCH + 2 * R

def heights(n):
    """random walk 1..5, mostly small moves with the odd jump, never standing still"""
    hs = [random.randint(1, ROWS)]
    for _ in range(n - 1):
        h = hs[-1]
        if random.random() < .3: nxt = random.randint(1, ROWS)
        else: nxt = h + random.choice([-2, -1, 1, 1, 2])
        nxt = max(1, min(ROWS, nxt))
        if nxt == h: nxt = h + 1 if h < ROWS else h - 1
        hs.append(nxt)
    hs[-1] = hs[0] if abs(hs[-2] - hs[0]) <= 3 else hs[-1]   # close the loop smoothly
    return hs

paths, targets = [], []
for c in range(COLS):
    n = LOOP_STEPS[c]; dur = n * STEP
    hs = heights(n)
    cx = R + c * PITCH
    for r in range(ROWS):
        cy = H - R - r * PITCH
        name = f"d{c}{r}"
        on0 = 1 if r == 0 or hs[0] > r else 0
        paths.append(f'    <path android:name="{name}" android:fillColor="{COLOR}" android:fillAlpha="{on0}" '
                     f'android:pathData="M{cx - R:.2f},{cy:.2f}a{R},{R} 0 1,0 {2 * R},0a{R},{R} 0 1,0 {-2 * R},0"/>')
        if r == 0: continue  # bottom dot always on
        kf = [(0.0, on0)]
        cur = on0
        for i in range(1, n + 1):
            v = 1 if hs[i % n] > r else 0
            if v != cur:
                t0 = i * STEP; t1 = min(dur, t0 + FADE)
                if t0 >= dur: break
                kf.append((t0 / dur, cur)); kf.append((t1 / dur, v)); cur = v
        if cur != on0:  # wrap back to the start state at the very end
            kf.append(((dur - FADE) / dur, cur)); kf.append((1.0, on0))
        elif kf[-1][0] < 1.0: kf.append((1.0, on0))
        if len(kf) <= 2 and all(k[1] == on0 for k in kf): continue
        frames = "\n".join(f'                    <keyframe android:fraction="{f:.4f}" android:value="{v}"/>' for f, v in kf)
        targets.append(f'''    <target android:name="{name}">
        <aapt:attr name="android:animation">
            <objectAnimator android:duration="{dur}" android:repeatCount="infinite" android:interpolator="@android:anim/linear_interpolator">
                <propertyValuesHolder android:propertyName="fillAlpha" android:valueType="floatType">
{frames}
                </propertyValuesHolder>
            </objectAnimator>
        </aapt:attr>
    </target>''')

xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/gen_eq.py - edit the script, not this file -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector android:width="{W:.1f}dp" android:height="{H:.1f}dp" android:viewportWidth="{W:.2f}" android:viewportHeight="{H:.2f}">
{chr(10).join(paths)}
        </vector>
    </aapt:attr>
{chr(10).join(targets)}
</animated-vector>
'''
out = os.path.join(os.path.dirname(__file__), "..", "app/src/main/res/drawable/eq_anim.xml")
open(out, "w").write(xml)
print(f"wrote {out}: {len(targets)} animated dots, {W:.1f}x{H:.1f}dp")
